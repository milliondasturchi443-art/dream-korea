import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma } from "../lib/db";
import { mutateLedger, initializePaymentMonth, monthId } from "../lib/payment-ledger";
import { accountTotals, operationSchema, paymentBillingMonth } from "../lib/payment-accounting";
import { GET, POST } from "../app/api/payments/ledger/route";
import { signSession } from "../lib/session";

// Explicitly opt-in, isolated database only. Never run fixtures in production.
const url = new URL(process.env.DATABASE_URL ?? "");
if (!/^dreamkorea_payment_test_\d+$/.test(url.pathname.slice(1))) throw new Error("Isolated test database required");

async function main() {
  const s = await prisma.user.create({ data: { name: "Payment integration student", email: `ledger-${randomUUID()}@example.test`, password: "test-only", role: "STUDENT", monthlyFee: 450000, lessonHours: 12 } });
  const other = await prisma.user.create({ data: { name: "Other student", email: `ledger-${randomUUID()}@example.test`, password: "test-only", role: "STUDENT", monthlyFee: 360000, lessonHours: 24 } });
  const teacher = await prisma.user.create({ data: { name: "Teacher A", email: `teacher-${randomUUID()}@example.test`, password: "test-only", role: "TEACHER" } });
  const group = await prisma.group.create({ data: { name: "Test group", teacherId: teacher.id } });
  await prisma.groupMember.create({ data: { groupId: group.id, userId: s.id } });
  const actor = "test-admin";
  assert.equal((await GET(new Request("http://localhost/api/payments/ledger"))).status, 401);
  const teacherToken = signSession({ ...teacher, tokenVersion: 0 });
  assert.equal((await GET(new Request("http://localhost/api/payments/ledger", { headers: { Authorization: `Bearer ${teacherToken}` } }))).status, 403);
  const admin = await prisma.user.create({ data: { name: "Test Admin", email: `admin-${randomUUID()}@example.test`, password: "test-only", role: "ADMIN" } });
  const adminToken = signSession({ ...admin, tokenVersion: 0 });
  const headers = { Authorization: `Bearer ${adminToken}`, "Content-Type": "application/json" };
  assert.equal((await POST(new Request("http://localhost/api/payments/ledger", { method: "POST", headers, body: JSON.stringify({ action: "PAYMENT", amount: -1 }) }))).status, 400);
  const op = (body: Record<string, unknown>) => mutateLedger(operationSchema.parse({ requestId: randomUUID(), userId: s.id, billingMonth: "2026-10", ...body }), actor);
  const totals = async (billingMonth: string) => {
    const a = await prisma.paymentMonth.findUnique({ where: { id: monthId(s.id, billingMonth) } });
    const payments = await prisma.payment.findMany({ where: { userId: s.id } });
    return accountTotals(a?.tuition ?? null, payments.filter(p => paymentBillingMonth(p) === billingMonth));
  };
  await op({ action: "TARIFF", tuition: 450000 });
  await op({ action: "PAYMENT", amount: 200000, operationDate: "2026-10-05" });
  assert.equal((await totals("2026-10")).debt, 250000);
  await op({ action: "PAYMENT", amount: 250000, operationDate: "2026-10-15" });
  assert.equal((await totals("2026-10")).debt, 0);
  const editable = await prisma.payment.findFirstOrThrow({ where: { userId: s.id, amount: 250000, operationType: "PAYMENT" } });
  await op({ action: "EDIT", paymentId: editable.id, amount: 300000, operationDate: "2026-10-16", note: "Corrected receipt" });
  const edited = await prisma.payment.findUniqueOrThrow({ where: { id: editable.id } });
  assert.equal(edited.amount, 300000);
  assert.equal(edited.operationDate, "2026-10-16");
  assert.equal(edited.note, "Corrected receipt");
  assert.equal((await totals("2026-10")).net, 500000);
  await op({ action: "REFUND", amount: 150000, operationDate: "2026-10-20" });
  assert.equal((await totals("2026-10")).net, 350000);
  await op({ action: "TARIFF", tuition: 420000, billingMonth: "2026-11", lessonHours: 12 });
  assert.equal((await totals("2026-11")).received, 0);
  assert.equal((await totals("2026-11")).debt, 420000);
  await op({ action: "PAYMENT", amount: 50000, operationDate: "2026-11-04" });
  assert.equal((await totals("2026-10")).net, 350000);
  assert.equal((await totals("2026-11")).received, 0);
  const retry = operationSchema.parse({ requestId: randomUUID(), action: "PAYMENT", userId: s.id, billingMonth: "2026-10", amount: 10000, operationDate: "2026-11-04" });
  const before = await prisma.payment.count();
  await Promise.all([mutateLedger(retry, actor), mutateLedger(retry, actor)]);
  assert.equal(await prisma.payment.count(), before + 1);
  await assert.rejects(() => mutateLedger({ ...retry, amount: 999 }, actor), /kaliti/);
  await assert.rejects(() => op({ action: "REFUND", amount: 999999, operationDate: "2026-11-04" }), /oshmasligi/);
  const concurrent = await Promise.allSettled([op({ action: "REFUND", amount: 250000, operationDate: "2026-11-04" }), op({ action: "REFUND", amount: 250000, operationDate: "2026-11-04" })]);
  assert.equal(concurrent.filter(r => r.status === "fulfilled").length, 1);
  assert.equal((await totals("2026-10")).net, 110000);
  const p = await prisma.payment.findFirstOrThrow({ where: { userId: s.id, amount: 250000, operationType: "PAYMENT" } });
  await assert.rejects(() => op({ action: "VOID", paymentId: p.id, note: "Test" }), /manfiy/);
  await op({ action: "TARIFF", userId: other.id, billingMonth: "2026-11", tuition: 360000, lessonHours: 24 });
  await op({ action: "PAYMENT", userId: other.id, billingMonth: "2026-11", amount: 360000, operationDate: "2026-11-04" });
  assert.equal((await totals("2026-11")).received, 0);
  await initializePaymentMonth("2026-12");
  const a = await prisma.paymentMonth.findUniqueOrThrow({ where: { id: monthId(s.id, "2026-12") } });
  assert.equal(a.tuition, 450000);
  assert.deepEqual(a.teacherIds, [teacher.id]);
  await op({ action: "TARIFF", billingMonth: "2026-11", tuition: 450000, setDefault: true });
  assert.equal((await totals("2026-10")).tuition, 450000);
  assert.equal((await prisma.paymentMonth.findUniqueOrThrow({ where: { id: a.id } })).tuition, 450000);
  const legacy = await prisma.payment.create({ data: { userId: s.id, amount: 120000, month: "unknown", method: "cash", status: "PAID" } });
  await assert.rejects(() => op({ action: "ASSIGN", paymentId: legacy.id }), /izohda/);
  await op({ action: "ASSIGN", paymentId: legacy.id, note: "Receipt explicitly says October" });
  assert.equal((await totals("2026-10")).net, 230000);
  const ledgerResponse = await GET(new Request("http://localhost/api/payments/ledger?billingMonth=2026-11", { headers }));
  assert.equal(ledgerResponse.status, 200);
  const ledger = await ledgerResponse.json();
  assert.equal(ledger.students.find((row: { id: string }) => row.id === s.id).received, 0);
  assert.equal(ledger.summary.received, 360000);
  assert.equal(ledger.chart.find((row: { billingMonth: string }) => row.billingMonth === "2026-10").refunded, 400000);
  console.log("PASS: persistence, partial/full payments, refunds, old-month receipts, separate students, snapshots, idempotency, concurrent refund limits, void protection");
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
